#!/bin/bash

# Plasma Version Detection & Compatibility Script
# Handles Plasma 5 vs Plasma 6 differences and weather data engines

# Colors for output
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}=== Plasma Version Detection & Compatibility Setup ===${NC}"

# Detect Plasma version
detect_plasma_version() {
    echo -e "${YELLOW}Detecting Plasma version...${NC}"
    
    # Method 1: Check plasmashell version
    if command -v plasmashell >/dev/null 2>&1; then
        local plasma_version=$(plasmashell --version 2>/dev/null | grep -oE '[0-9]+\.[0-9]+' | head -1)
        if [[ "$plasma_version" =~ ^6\. ]]; then
            echo -e "${GREEN}✓ Plasma 6 detected (version $plasma_version)${NC}"
            return 6
        elif [[ "$plasma_version" =~ ^5\. ]]; then
            echo -e "${GREEN}✓ Plasma 5 detected (version $plasma_version)${NC}"
            return 5
        fi
    fi
    
    # Method 2: Check for Plasma 6 specific files
    if [ -f "/usr/share/plasma/plasmoids/org.kde.plasma.desktop/metadata.json" ]; then
        local desktop_version=$(jq -r '.KPlugin.Version' /usr/share/plasma/plasmoids/org.kde.plasma.desktop/metadata.json 2>/dev/null)
        if [[ "$desktop_version" =~ ^6\. ]]; then
            echo -e "${GREEN}✓ Plasma 6 detected (desktop version $desktop_version)${NC}"
            return 6
        fi
    fi
    
    # Method 3: Check package manager
    if command -v kpackagetool6 >/dev/null 2>&1; then
        echo -e "${GREEN}✓ Plasma 6 detected (kpackagetool6 present)${NC}"
        return 6
    elif command -v kpackagetool5 >/dev/null 2>&1; then
        echo -e "${GREEN}✓ Plasma 5 detected (kpackagetool5 present)${NC}"
        return 5
    fi
    
    # Default fallback
    echo -e "${YELLOW}⚠ Could not determine Plasma version, assuming Plasma 5${NC}"
    return 5
}

# Detect available weather data engines
detect_weather_engines() {
    echo -e "${YELLOW}Detecting available weather data engines...${NC}"
    
    local engines_found=()
    local plasma_data_dir=""
    
    # Find plasma data directory
    for dir in "/usr/share/plasma/dataengines" "$HOME/.local/share/plasma/dataengines" "/usr/lib/qt5/plugins/plasma/dataengine" "/usr/lib/qt6/plugins/plasma/dataengine"; do
        if [ -d "$dir" ]; then
            plasma_data_dir="$dir"
            break
        fi
    done
    
    if [ -n "$plasma_data_dir" ]; then
        echo "Checking data engines in: $plasma_data_dir"
        
        # Check for weather engines
        if [ -f "$plasma_data_dir/plasma_engine_weather.so" ] || [ -d "$plasma_data_dir/weather" ]; then
            engines_found+=("weather")
            echo -e "${GREEN}✓ Standard weather engine found${NC}"
        fi
        
        if [ -f "$plasma_data_dir/plasma_engine_weatherion.so" ] || [ -d "$plasma_data_dir/weatherion" ]; then
            engines_found+=("weatherion")
            echo -e "${GREEN}✓ WeatherIon engine found${NC}"
        fi
    fi
    
    # Check via qdbus if available
    if command -v qdbus >/dev/null 2>&1; then
        local available_engines=$(qdbus org.kde.kded5 /kded org.kde.kded5.loadedModules 2>/dev/null | grep -i weather)
        if [ -n "$available_engines" ]; then
            echo -e "${GREEN}✓ Weather modules loaded in kded: $available_engines${NC}"
        fi
    fi
    
    if [ ${#engines_found[@]} -eq 0 ]; then
        echo -e "${RED}❌ No weather data engines found${NC}"
        echo "You may need to install weather data providers:"
        echo "  Ubuntu/Debian: sudo apt install plasma-dataengines-addons"
        echo "  Arch/Manjaro: sudo pacman -S kdeplasma-addons"
        engines_found+=("weather") # fallback assumption
    fi
    
    echo "${engines_found[@]}"
}

# Create version-specific configuration
create_version_config() {
    local plasma_version=$1
    local weather_engines=("${@:2}")
    
    echo -e "${YELLOW}Creating version-specific configuration...${NC}"
    
    cat > plasma-config.env << EOF
# Plasma Version Configuration
# Auto-generated by plasma version detector

PLASMA_VERSION=$plasma_version
WEATHER_ENGINES="${weather_engines[*]}"

# Version-specific commands
EOF

    if [ "$plasma_version" -eq 6 ]; then
        cat >> plasma-config.env << EOF
PLASMA_RESTART_CMD="killall plasmashell; plasmashell &"
PACKAGE_INSTALL_CMD="kpackagetool6 --install"
PACKAGE_REMOVE_CMD="kpackagetool6 --remove"
PACKAGE_UPGRADE_CMD="kpackagetool6 --upgrade"
PLASMA_SHELL_CMD="plasmashell"
QML_IMPORT_VERSION="import org.kde.plasma.core as PlasmaCore"
KIRIGAMI_VERSION="import org.kde.kirigami as Kirigami"
EOF
    else
        cat >> plasma-config.env << EOF
PLASMA_RESTART_CMD="killall plasmashell; kstart5 plasmashell &"
PACKAGE_INSTALL_CMD="plasmapkg2 --install"
PACKAGE_REMOVE_CMD="plasmapkg2 --remove"
PACKAGE_UPGRADE_CMD="plasmapkg2 --upgrade"
PLASMA_SHELL_CMD="kstart5 plasmashell"
QML_IMPORT_VERSION="import org.kde.plasma.core 2.1 as PlasmaCore"
KIRIGAMI_VERSION="import org.kde.kirigami 2.4 as Kirigami"
EOF
    fi
    
    echo -e "${GREEN}✓ Configuration saved to plasma-config.env${NC}"
}

# Update QML files for detected version
update_qml_imports() {
    local plasma_version=$1
    
    echo -e "${YELLOW}Updating QML imports for Plasma $plasma_version...${NC}"
    
    if [ "$plasma_version" -eq 6 ]; then
        # Update to Plasma 6 syntax
        if [ -f "main.qml" ]; then
            sed -i 's/import org\.kde\.plasma\.core 2\.1 as PlasmaCore/import org.kde.plasma.core as PlasmaCore/g' main.qml
            sed -i 's/import org\.kde\.plasma\.components 3\.0 as PlasmaComponents3/import org.kde.plasma.components as PlasmaComponents/g' main.qml
            sed -i 's/import org\.kde\.kirigami 2\.4 as Kirigami/import org.kde.kirigami as Kirigami/g' main.qml
            echo -e "${GREEN}✓ Updated main.qml for Plasma 6${NC}"
        fi
        
        if [ -f "config.qml" ]; then
            sed -i 's/import org\.kde\.kirigami 2\.4 as Kirigami/import org.kde.kirigami as Kirigami/g' config.qml
            echo -e "${GREEN}✓ Updated config.qml for Plasma 6${NC}"
        fi
    else
        # Ensure Plasma 5 syntax
        echo -e "${GREEN}✓ QML files are compatible with Plasma 5${NC}"
    fi
}

# Create weather engine compatibility layer
create_weather_compatibility() {
    local weather_engines=("$@")
    
    echo -e "${YELLOW}Creating weather engine compatibility layer...${NC}"
    
    cat > WeatherCompatibility.qml << 'EOF'
// Weather Engine Compatibility Layer
import QtQuick 2.15
import org.kde.plasma.core 2.1 as PlasmaCore

QtObject {
    id: weatherCompat
    
    property string primaryEngine: "weather"
    property var availableEngines: []
    
    // Auto-detect best weather engine
    function detectBestEngine() {
        var engines = ["weather", "weatherion", "bbcukmet", "envcan", "noaa", "wettercom"]
        
        for (var i = 0; i < engines.length; i++) {
            if (testEngine(engines[i])) {
                primaryEngine = engines[i]
                console.log("Using weather engine:", primaryEngine)
                return primaryEngine
            }
        }
        
        console.warn("No weather engines found, using default")
        return "weather"
    }
    
    function testEngine(engineName) {
        // Test if engine is available
        try {
            var testSource = Qt.createQmlObject(
                'import org.kde.plasma.core 2.1 as PlasmaCore; ' +
                'PlasmaCore.DataSource { engine: "' + engineName + '" }',
                weatherCompat
            )
            if (testSource) {
                testSource.destroy()
                return true
            }
        } catch (e) {
            console.log("Engine", engineName, "not available:", e)
        }
        return false
    }
    
    // Create compatible weather data source
    function createWeatherSource(location) {
        return Qt.createQmlObject(
            'import org.kde.plasma.core 2.1 as PlasmaCore; ' +
            'PlasmaCore.DataSource { ' +
            '    engine: "' + primaryEngine + '"; ' +
            '    connectedSources: ["' + location + '"]; ' +
            '    interval: 30000 ' +
            '}',
            weatherCompat
        )
    }
    
    Component.onCompleted: {
        detectBestEngine()
    }
}
EOF
    
    echo -e "${GREEN}✓ Weather compatibility layer created${NC}"
}

# Update install scripts with version-specific commands
update_install_scripts() {
    local plasma_version=$1
    
    echo -e "${YELLOW}Updating install scripts for Plasma $plasma_version...${NC}"
    
    # Load config
    source plasma-config.env
    
    # Update install_script.sh
    if [ -f "install_script.sh" ]; then
        # Update restart command
        sed -i "s|killall plasmashell; kstart5 plasmashell|$PLASMA_RESTART_CMD|g" install_script.sh
        sed -i "s|killall plasmashell; plasmashell|$PLASMA_RESTART_CMD|g" install_script.sh
        
        # Update package commands
        sed -i "s|plasmapkg2 --install|$PACKAGE_INSTALL_CMD|g" install_script.sh
        sed -i "s|plasmapkg2 --upgrade|$PACKAGE_UPGRADE_CMD|g" install_script.sh
        
        echo -e "${GREEN}✓ Updated install_script.sh${NC}"
    fi
    
    # Update advanced_effects_setup.sh
    if [ -f "advanced_effects_setup.sh" ]; then
        sed -i "s|killall plasmashell; kstart5 plasmashell|$PLASMA_RESTART_CMD|g" advanced_effects_setup.sh
        sed -i "s|killall plasmashell; plasmashell|$PLASMA_RESTART_CMD|g" advanced_effects_setup.sh
        echo -e "${GREEN}✓ Updated advanced_effects_setup.sh${NC}"
    fi
}

# Create system-specific installation guide
create_install_guide() {
    local plasma_version=$1
    local weather_engines=("${@:2}")
    
    cat > INSTALLATION_GUIDE.md << EOF
# Weather Widget Installation Guide

## System Configuration
- **Plasma Version**: $plasma_version
- **Available Weather Engines**: ${weather_engines[*]}
- **System**: $(uname -m) $(lsb_release -d -s 2>/dev/null || echo "Unknown")

## Installation Commands

### 1. Install the widget
\`\`\`bash
# Make scripts executable
chmod +x install_script.sh advanced_effects_setup.sh

# Run installation
./install_script.sh
./advanced_effects_setup.sh
\`\`\`

### 2. Restart Plasma
\`\`\`bash
$PLASMA_RESTART_CMD
\`\`\`

### 3. Add Widget
- Right-click on desktop or panel
- Select "Add Widgets..."
- Search for "Weather Effects Widget"
- Add to your desktop or panel

## Troubleshooting

### If weather data doesn't load:
1. Check available weather engines:
   \`\`\`bash
   qdbus org.kde.kded5 /kded org.kde.kded5.loadedModules | grep -i weather
   \`\`\`

2. Install weather data engines:
   - **Ubuntu/Debian**: \`sudo apt install plasma-dataengines-addons\`
   - **Arch/Manjaro**: \`sudo pacman -S kdeplasma-addons\`

### If desktop effects don't work:
1. Enable compositor: System Settings > Desktop Effects
2. Check KWin effects are available:
   \`\`\`bash
   qdbus org.kde.kwin /KWin org.kde.kwin.Compositing.active
   \`\`\`

## Version-Specific Notes

EOF

    if [ "$plasma_version" -eq 6 ]; then
        cat >> INSTALLATION_GUIDE.md << EOF
### Plasma 6 Specific:
- Uses \`kpackagetool6\` for package management
- Updated QML imports (no version numbers)
- Direct \`plasmashell\` restart (no kstart5)

EOF
    else
        cat >> INSTALLATION_GUIDE.md << EOF
### Plasma 5 Specific:
- Uses \`plasmapkg2\` for package management  
- Traditional QML imports with version numbers
- Restart with \`kstart5 plasmashell\`

EOF
    fi
    
    echo -e "${GREEN}✓ Installation guide created: INSTALLATION_GUIDE.md${NC}"
}

# Main execution
main() {
    detect_plasma_version
    local plasma_version=$?
    
    local weather_engines=($(detect_weather_engines))
    
    create_version_config $plasma_version "${weather_engines[@]}"
    update_qml_imports $plasma_version
    create_weather_compatibility "${weather_engines[@]}"
    update_install_scripts $plasma_version
    create_install_guide $plasma_version "${weather_engines[@]}"
    
    echo ""
    echo -e "${BLUE}=== Configuration Complete! ===${NC}"
    echo -e "${GREEN}Your system is configured for Plasma $plasma_version${NC}"
    echo -e "${GREEN}Weather engines: ${weather_engines[*]}${NC}"
    echo ""
    echo -e "${YELLOW}Next steps:${NC}"
    echo "1. Review: INSTALLATION_GUIDE.md"
    echo "2. Run: ./install_script.sh"
    echo "3. Run: ./advanced_effects_setup.sh" 
    echo ""
    echo -e "${BLUE}Files created:${NC}"
    echo "• plasma-config.env - Version configuration"
    echo "• WeatherCompatibility.qml - Engine compatibility"
    echo "• INSTALLATION_GUIDE.md - System-specific guide"
}

# Run main function
main "$@"